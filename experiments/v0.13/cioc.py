"""V0.13: quorum diagnosis under independent, replayed and colluding reports.

Limited toy benchmark. World supplies a finite behavior fixture and host-based
challenger; reports are generated by damageable policies, not inferred from code
identity. There is no trusted organism-level ground-truth interface.
"""
from __future__ import annotations
from dataclasses import dataclass, field
from itertools import product

ALPHABET = ('NOOP', 'SENSE', 'REPORT', 'REPORT_ALT', 'INVERT', 'SILENCE')
CANONICAL = ('SENSE', 'REPORT')


def execute(code: tuple[str, ...] | None, observed_fault: bool) -> bool | None:
    """Run two-stage sensor/report program. None means abstain/no report."""
    if code is None: return None
    evidence = None
    output = None
    for op in code:
        if op == 'SENSE': evidence = observed_fault
        elif op == 'INVERT' and evidence is not None: evidence = not evidence
        elif op in ('REPORT', 'REPORT_ALT') and evidence is not None: output = evidence
        elif op == 'SILENCE': output = None
    return output


def witness_contract(code: tuple[str, ...] | None) -> bool:
    return execute(code, True) is True and execute(code, False) is False


@dataclass
class EvidenceWorld:
    budget: int = 400
    witnesses: dict[str, tuple[str, ...] | None] = field(default_factory=lambda: {
        'A': CANONICAL, 'B': ('SENSE', 'REPORT_ALT'), 'C': CANONICAL})
    target_code: tuple[str, ...] | None = CANONICAL
    witness_weights: dict[str, int] = field(default_factory=lambda: {'A': 1, 'B': 1, 'C': 1})
    fragments: dict[str, str] = field(default_factory=lambda: {'A': 'SENSE', 'B': 'SENSE', 'C': 'SENSE'})
    events: list[dict] = field(default_factory=list)
    internal_repairs: int = 0
    external_repairs: int = 0
    epoch: int = 0
    processed_epochs: set[int] = field(default_factory=set)
    allow_recovery: bool = True

    def consume(self, n=1) -> bool:
        if self.budget < n: return False
        self.budget -= n
        return True

    def observed(self) -> bool:
        # finite-world canary. This is not an interface the organism can query
        # for true target health. Witness policies receive canary effects.
        return not witness_contract(self.target_code)

    def report(self, name: str, epoch: int, fault: bool) -> dict | None:
        if not self.consume(): return None
        result = execute(self.witnesses[name], fault)
        if result is None: return None
        return {'name': name, 'epoch': epoch, 'fault': result}

    def collect(self, *, injected: list[dict] | None = None) -> list[dict]:
        self.epoch += 1
        fault = self.observed()
        reports = [r for name in self.witnesses if (r := self.report(name, self.epoch, fault)) is not None]
        reports.extend(injected or [])
        self.events.append({'event':'evidence', 'epoch':self.epoch, 'reports':reports})
        return reports

    def adjudicate(self, reports: list[dict]) -> bool | None:
        """One vote per registered witness at the current epoch; conflict abstains."""
        if self.epoch in self.processed_epochs: return None
        valid = {}
        for report in reports:
            name, epoch, fault = report.get('name'), report.get('epoch'), report.get('fault')
            if name not in self.witnesses or epoch != self.epoch or type(fault) is not bool:
                continue
            if name in valid and valid[name] != fault:
                valid[name] = None  # a contradictory witness loses its vote
            elif name not in valid:
                valid[name] = fault
        # Witness count, NOT weights; no Sybil voting via extra identities.
        votes = [v for v in valid.values() if v is not None]
        if len(votes) < 2: return None
        trues, falses = votes.count(True), votes.count(False)
        if trues < 2 and falses < 2: return None
        self.processed_epochs.add(self.epoch)
        decision = trues > falses
        self.events.append({'event':'decision', 'epoch':self.epoch, 'fault':decision})
        return decision

    def repair(self, reports: list[dict]) -> bool:
        decision = self.adjudicate(reports)
        if decision is not True or not self.allow_recovery: return False
        # Even with a verdict, candidates are tested by independent canaries.
        # One witness contributes only a one-instruction fragment, not a backup.
        if not self.consume(2): return False
        prefixes = [self.fragments.get(n) for n in self.witnesses if self.witnesses[n] is not None]
        if prefixes.count('SENSE') < 2: return False
        for tail in ALPHABET:
            if not self.consume(1): return False
            candidate = ('SENSE', tail)
            if witness_contract(candidate):
                if not self.consume(3): return False
                self.target_code = candidate
                self.internal_repairs += 1
                self.events.append({'event':'install', 'candidate':candidate})
                return True
        return False

    def step(self, injected=None):
        return self.repair(self.collect(injected=injected))

    def external_restore(self):
        self.target_code = CANONICAL
        self.external_repairs += 1


def scenarios():
    out={}
    def result(w,label,inject=None):
        repaired=w.step(injected=inject)
        out[label]={'repair':repaired,'healthy':witness_contract(w.target_code),
                    'internal':w.internal_repairs,'remaining_budget':w.budget}
    w=EvidenceWorld(target_code=('SENSE','SILENCE'));result(w,'single_fault')
    w=EvidenceWorld();result(w,'healthy')
    w=EvidenceWorld(target_code=('SENSE','SILENCE'));w.witnesses['A']=('SENSE','INVERT','REPORT');result(w,'one_byzantine')
    w=EvidenceWorld(target_code=('SENSE','SILENCE'));w.witnesses['A']=('SENSE','INVERT','REPORT');w.witnesses['B']=('SENSE','INVERT','REPORT');result(w,'two_byzantine')
    w=EvidenceWorld(target_code=('SENSE','SILENCE'));w.witnesses['A']=None;w.witnesses['B']=None;result(w,'quorum_lost')
    w=EvidenceWorld(target_code=('SENSE','SILENCE'));result(w,'replayed_report',inject=[{'name':'A','epoch':0,'fault':False}])
    w=EvidenceWorld(target_code=('SENSE','SILENCE'));w.fragments.clear();result(w,'missing_fragments')
    w=EvidenceWorld(target_code=('SENSE','SILENCE'),budget=3);result(w,'low_budget')
    w=EvidenceWorld(target_code=('SENSE','SILENCE'),allow_recovery=False);result(w,'recovery_disabled')
    w=EvidenceWorld(target_code=('SENSE','SILENCE'));w.external_restore();result(w,'external_only')
    return out
